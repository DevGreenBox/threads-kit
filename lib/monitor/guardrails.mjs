/**
 * Единая точка, через которую проходит КАЖДАЯ отправка.
 *
 * Использование:
 *   const пр = new Предохранители({ конфиг });
 *   const вердикт = пр.проверитьОтвет({ текст, postId, author, threadId });
 *   if (!вердикт.можно) { ...журнал уже записан... }
 *   else { await клиент.publishReply(...); пр.зафиксироватьОтправку({...}); }
 *
 * ⚠️ Порядок обязателен: проверка → отправка → фиксация. Фиксация отдельным
 * шагом намеренно: если отправка упала, действие не должно попасть в историю
 * как состоявшееся, иначе счётчики поплывут.
 */
export class Предохранители {
  constructor({
    конфиг = {},
    путьСостояния = 'state/guardrails.json',
    путьЖурнала = 'state/actions.jsonl',
    журнал = null,
    сейчас = () => Date.now(),
    случайное = Math.random,
  } = {}) {
    this.наст = this._собратьНастройки(конфиг);
    this.путьСостояния = resolve(путьСостояния);
    this.журнал = журнал || new Журнал(путьЖурнала);
    this._сейчас = сейчас;
    this._случайное = случайное;

    this.состояние = читатьJSON(this.путьСостояния, {
      версия: 1,
      стопКран: null,      // {время, причина, детали} — null значит «работаем»
      отправки: [],        // [{время, текст, postId, author, threadId}]
      следующаяНеРанее: 0, // мс эпохи: человеческий ритм
    });
    if (!Array.isArray(this.состояние.отправки)) this.состояние.отправки = [];
  }

  /**
   * Сливает ПО_УМОЛЧАНИЮ + конфиг и ЗАЖИМАЕТ по ЖЁСТКОМУ_МАКСИМУМУ.
   *
   * Это и есть «зашитый максимум, который нельзя превысить правкой конфига»:
   * конфиг проходит через Math.min для лимитов и Math.max для интервалов.
   * Попытка поставить 500 ответов в сутки молча превратится в 80,
   * и факт зажима попадёт в журнал (см. this.зажатые).
   */
  _собратьНастройки(конфиг) {
    const c = { ...ПО_УМОЛЧАНИЮ, ...(конфиг || {}) };
    const зажатые = [];
    const вниз = (имя, максимум) => {
      const было = Number(c[имя]);
      const стало = Math.min(Number.isFinite(было) ? было : максимум, максимум);
      if (Number.isFinite(было) && было > максимум) зажатые.push({ имя, было, стало, предел: максимум });
      return Math.max(0, стало);
    };
    const вверх = (имя, минимум) => {
      const было = Number(c[имя]);
      const стало = Math.max(Number.isFinite(было) ? было : минимум, минимум);
      if (Number.isFinite(было) && было < минимум) зажатые.push({ имя, было, стало, предел: минимум });
      return стало;
    };

    const итог = {
      ...c,
      ответовВСутки: вниз('ответовВСутки', ЖЁСТКИЙ_МАКСИМУМ.ответовВСутки),
      постовВСутки: вниз('постовВСутки', ЖЁСТКИЙ_МАКСИМУМ.постовВСутки),
      поисковыхЗапросовВСутки: вниз('поисковыхЗапросовВСутки', ЖЁСТКИЙ_МАКСИМУМ.поисковыхЗапросовВСутки),
      ответовОдномуАвторуВНеделю: вниз('ответовОдномуАвторуВНеделю', ЖЁСТКИЙ_МАКСИМУМ.ответовОдномуАвторуВНеделю),
      ответовВОднуВеткуВсего: вниз('ответовВОднуВеткуВсего', ЖЁСТКИЙ_МАКСИМУМ.ответовВОднуВеткуВсего),
      минимальныйИнтервалСек: вверх('минимальныйИнтервалСек', ЖЁСТКИЙ_МАКСИМУМ.минимальныйИнтервалСек),
      // Порог схожести: конфиг может сделать СТРОЖЕ (меньше), но не мягче.
      максСхожесть: вниз('максСхожесть', ЖЁСТКИЙ_МАКСИМУМ.максСхожесть),
      окноСхожестиДней: вверх('окноСхожестиДней', 1),
    };
    this.зажатые = зажатые;
    return итог;
  }

  _сохранить() {
    писатьJSON(this.путьСостояния, this.состояние);
  }

  // ── стоп-кран ──

  /** Опущен ли стоп-кран. */
  стопКранОпущен() {
    return Boolean(this.состояние.стопКран);
  }

  /**
   * ОПУСТИТЬ СТОП-КРАН: полная остановка всей активности.
   *
   * Вызывается при первом признаке беды: action block, неизвестная ошибка API,
   * подозрительный ответ площадки. Снимается ТОЛЬКО руками человека
   * (снятьСтопКран или удаление поля в state/guardrails.json) — автоматического
   * возобновления нет намеренно: если автоматика сама себя разблокирует, она
   * продолжит делать то, из-за чего её заблокировали.
   */
  опуститьСтопКран(причина, детали = {}) {
    if (this.состояние.стопКран) return this.состояние.стопКран;
    const запись = {
      время: new Date(this._сейчас()).toISOString(),
      причина: String(причина),
      детали,
    };
    this.состояние.стопКран = запись;
    this._сохранить();
    this.журнал.записать({
      событие: 'СТОП_КРАН_ОПУЩЕН',
      причина: запись.причина,
      детали,
      комментарий:
        'Вся активность остановлена. Возобновление только вручную человеком ' +
        'после разбора причины.',
    });
    return запись;
  }

  /** Снять стоп-кран. Только осознанное действие человека. */
  снятьСтопКран({ кто = 'человек', обоснование = '' } = {}) {
    const было = this.состояние.стопКран;
    this.состояние.стопКран = null;
    this._сохранить();
    this.журнал.записать({ событие: 'стоп_кран_снят', кто, обоснование, было });
    return было;
  }

  /**
   * Разбор ошибки API: решает, это стоп-кран или переживаемая ситуация.
   *
   * Логика:
   *   ОшибкаЛимита  — норма площадки, ждём. Стоп-кран НЕ опускаем.
   *   ОшибкаТокена  — стоп-кран: без человека дальше никак.
   *   всё остальное — стоп-кран: неизвестный ответ трактуем как худший случай,
   *                   потому что именно так выглядит action block.
   */
  разобратьОшибкуAPI(ошибка) {
    const имя = ошибка?.name || 'Error';
    const сообщение = String(ошибка?.message || ошибка);

    if (имя === 'ОшибкаЛимита') {
      this.журнал.записать({
        событие: 'лимит_площадки',
        сообщение,
        действие: 'ждём, стоп-кран не опускаем',
      });
      return { стопКран: false, ждать: true };
    }

    const признакиБлока = /action block|temporarily blocked|restricted|spam|policy|unusual/i.test(сообщение);

    this.опуститьСтопКран(
      имя === 'ОшибкаТокена'
        ? 'Токен доступа отвергнут площадкой'
        : признакиБлока
          ? 'Ответ площадки похож на блокировку действий (action block)'
          : 'Неизвестный ответ API — трактуем как худший случай',
      { имя, сообщение },
    );
    return { стопКран: true, ждать: false };
  }

  // ── счётчики ──

  _отправкиЗа(мс) {
    const порог = this._сейчас() - мс;
    return this.состояние.отправки.filter((о) => о.время > порог);
  }

  /** Сводка по расходу бюджета: что показывать человеку. */
  бюджет() {
    const заСутки = this._отправкиЗа(86400000).length;
    return {
      ответовЗаСутки: заСутки,
      потолокОтветов: this.наст.ответовВСутки,
      осталосьОтветов: Math.max(0, this.наст.ответовВСутки - заСутки),
      жёсткийМаксимум: ЖЁСТКИЙ_МАКСИМУМ.ответовВСутки,
      зажатыеНастройки: this.зажатые,
      стопКран: this.состояние.стопКран,
      следующаяНеРанее: this.состояние.следующаяНеРанее
        ? new Date(this.состояние.следующаяНеРанее).toISOString()
        : null,
    };
  }

  // ── главная проверка ──

  /**
   * Можно ли отправить этот ответ прямо сейчас.
   *
   * Порядок проверок — от самых дешёвых и категоричных к дорогим.
   * Возвращает {можно, причина, код, детали}. Любой отказ пишется в журнал
   * с причиной: журнал отказов — это и есть отчётность предохранителей.
   */
  проверитьОтвет({ текст, postId, author = null, threadId = null, сейчас = null } = {}) {
    const t = сейчас ?? this._сейчас();
    const отказ = (код, причина, детали = {}) => {
      this.журнал.записать({
        событие: 'ЗАБЛОКИРОВАНО',
        код,
        причина,
        postId: postId ?? null,
        author,
        threadId,
        детали,
        фрагмент: String(текст || '').slice(0, 120),
      });
      return { можно: false, код, причина, детали };
    };

    // 1. Стоп-кран. Категорично и раньше всего.
    if (this.стопКранОпущен()) {
      return отказ(
        'СТОП_КРАН',
        'Опущен стоп-кран: активность остановлена до разбора человеком. ' +
          `Причина остановки: ${this.состояние.стопКран.причина}`,
        { стопКран: this.состояние.стопКран },
      );
    }

    // 2. Текст вообще есть и адекватной длины.
    const чистый = String(текст || '').trim();
    if (!чистый) return отказ('ПУСТО', 'Пустой текст ответа.');
    if (чистый.length > this.наст.максДлинаОтвета) {
      return отказ('ДЛИННО', `Ответ ${чистый.length} символов, лимит площадки ${this.наст.максДлинаОтвета}.`);
    }
    if (чистый.length < this.наст.минДлинаОтвета) {
      return отказ(
        'КОРОТКО',
        `Ответ ${чистый.length} символов — короче ${this.наст.минДлинаОтвета}. ` +
          'Короткие ответы («согласен», «отличный кейс») площадка считает шаблонными, ' +
          'а читателю они не дают ничего.',
      );
    }
    if (!postId) return отказ('НЕТ_ПОСТА', 'Не указан id поста, которому отвечаем.');

    // 3. Ночная пауза. Круглосуточная активность — прямой признак бота.
    const час = часВТаймзоне(this.наст.таймзона, new Date(t));
    const { часНачала: с, часОкончания: до } = this.наст;
    const бодрствуем = с <= до ? час >= с && час < до : час >= с || час < до;
    if (!бодрствуем) {
      return отказ(
        'НОЧЬ',
        `Сейчас ${час}:00 по ${this.наст.таймзона}, окно активности ${с}:00–${до}:00. ` +
          'Ночью не пишем: активность без сна — признак автоматики.',
        { час, таймзона: this.наст.таймзона },
      );
    }

    // 4. Человеческий ритм: пауза с разбросом.
    if (t < (this.состояние.следующаяНеРанее || 0)) {
      const ждатьСек = Math.ceil(((this.состояние.следующаяНеРанее) - t) / 1000);
      return отказ(
        'РИТМ',
        `Слишком рано: до следующего ответа ещё ${ждатьСек} с. ` +
          'Интервал между ответами намеренно неровный — ровный ритм выдаёт бота.',
        { ждатьСек },
      );
    }

    // 5. Суточный бюджет — 5–10% от разрешённого площадкой.
    const заСутки = this._отправкиЗа(86400000);
    if (заСутки.length >= this.наст.ответовВСутки) {
      return отказ(
        'БЮДЖЕТ_СУТКИ',
        `Исчерпан суточный бюджет: ${заСутки.length} из ${this.наст.ответовВСутки} ответов. ` +
          `Площадка разрешает 1000, но мы держим ${this.наст.ответовВСутки} намеренно.`,
        { израсходовано: заСутки.length, потолок: this.наст.ответовВСутки },
      );
    }

    // 6. Лимит на одного автора. Ходить за одним человеком — преследование.
    if (author) {
      const заНеделю = this._отправкиЗа(7 * 86400000).filter(
        (о) => о.author && о.author.toLowerCase() === String(author).toLowerCase(),
      );
      if (заНеделю.length >= this.наст.ответовОдномуАвторуВНеделю) {
        return отказ(
          'ЛИМИТ_АВТОРА',
          `Автору @${author} за неделю уже отвечали ${заНеделю.length} раз ` +
            `(предел ${this.наст.ответовОдномуАвторуВНеделю}). Повторные приходы к одному ` +
            'человеку выглядят как преследование и помечаются площадкой.',
          { author, было: заНеделю.length },
        );
      }
    }

    // 7. Лимит в одну ветку: второй ответ в ту же ветку — спор или спам.
    if (threadId) {
      const вВетке = this.состояние.отправки.filter((о) => о.threadId === threadId);
      if (вВетке.length >= this.наст.ответовВОднуВеткуВсего) {
        return отказ(
          'ЛИМИТ_ВЕТКИ',
          `В эту ветку уже отправлено ${вВетке.length} ответов ` +
            `(предел ${this.наст.ответовВОднуВеткуВсего}). Второй ответ в ветку — ` +
            'это либо спор, либо спам.',
          { threadId },
        );
      }
    }

    // 8. Уже отвечали именно этому посту — идемпотентность.
    if (this.состояние.отправки.some((о) => о.postId === postId)) {
      return отказ('УЖЕ_ОТВЕЧАЛИ', `Этому посту (${postId}) ответ уже отправляли.`);
    }

    // 9. НЕПОХОЖЕСТЬ. Прямая защита от главного признака спама.
    const окно = this._отправкиЗа(this.наст.окноСхожестиДней * 86400000);
    let худшая = { значение: 0, с: null };
    for (const прошлая of окно) {
      const s = схожесть(чистый, прошлая.текст);
      if (s > худшая.значение) худшая = { значение: s, с: прошлая };
    }
    if (худшая.значение >= this.наст.максСхожесть) {
      return отказ(
        'ПОХОЖЕ',
        `Ответ похож на уже отправленный: схожесть ${худшая.значение.toFixed(2)} ` +
          `при пороге ${this.наст.максСхожесть}. Повтор похожих ответов у разных ` +
          'авторов — тот самый признак, за который Threads считает аккаунт ' +
          'неаутентичным. Нужен ответ по существу именно этого поста, а не ' +
          'перефразировка прошлого.',
        {
          схожесть: Number(худшая.значение.toFixed(4)),
          порог: this.наст.максСхожесть,
          похожНа: {
            postId: худшая.с?.postId ?? null,
            author: худшая.с?.author ?? null,
            время: худшая.с ? new Date(худшая.с.время).toISOString() : null,
            фрагмент: String(худшая.с?.текст || '').slice(0, 120),
          },
        },
      );
    }

    return {
      можно: true,
      код: 'ОК',
      причина: 'Все предохранители пройдены.',
      детали: {
        максСхожестьСПрошлыми: Number(худшая.значение.toFixed(4)),
        ответовЗаСутки: заСутки.length,
        потолокСуток: this.наст.ответовВСутки,
      },
    };
  }

  /**
   * Зафиксировать СОСТОЯВШУЮСЯ отправку.
   * Вызывать только после успешного ответа API: иначе счётчики разойдутся
   * с реальностью и бюджет будет расходоваться на неудачи.
   */
  зафиксироватьОтправку({ текст, postId, author = null, threadId = null, replyId = null }) {
    const t = this._сейчас();
    this.состояние.отправки.push({
      время: t,
      текст: String(текст),
      postId,
      author,
      threadId,
      replyId,
    });

    // Следующая отправка — не раньше чем через интервал + случайный разброс.
    // Разброс обязателен: ровно 10 минут между ответами читается как расписание.
    const разброс = Math.floor(this._случайное() * (this.наст.разбросИнтервалаСек || 0));
    this.состояние.следующаяНеРанее = t + (this.наст.минимальныйИнтервалСек + разброс) * 1000;

    // История чистится: старше 90 дней не нужна для проверок, а файл растёт.
    const порог = t - 90 * 86400000;
    this.состояние.отправки = this.состояние.отправки.filter((о) => о.время > порог);

    this._сохранить();
    this.журнал.записать({
      событие: 'ОТПРАВЛЕНО',
      postId,
      author,
      threadId,
      replyId,
      длина: String(текст).length,
      фрагмент: String(текст).slice(0, 200),
      следующаяНеРанее: new Date(this.состояние.следующаяНеРанее).toISOString(),
    });
    return { следующаяНеРанее: this.состояние.следующаяНеРанее };
  }

  /** Разрешение на поисковый запрос: отдельный, более щедрый бюджет. */
  проверитьПоиск({ запрос: фраза = '', сейчас = null } = {}) {
    if (this.стопКранОпущен()) {
      this.журнал.записать({
        событие: 'ЗАБЛОКИРОВАНО',
        код: 'СТОП_КРАН',
        причина: 'Поиск остановлен: опущен стоп-кран.',
        запрос: фраза,
      });
      return { можно: false, код: 'СТОП_КРАН', причина: 'Опущен стоп-кран.' };
    }
    return { можно: true, код: 'ОК', причина: 'Поиск разрешён.' };
  }
}

export default Предохранители;
