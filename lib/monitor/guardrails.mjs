/**
 * Приводит текст к виду, в котором сравнение имеет смысл.
 *
 * Специально агрессивная: убирает регистр, пунктуацию, эмодзи, ссылки,
 * @упоминания, ё→е и стягивает пробелы. Цель — чтобы «Отличный кейс! 🔥» и
 * «отличный кейс» считались одним текстом. Спамер меняет ровно эти детали,
 * думая, что сделал разные комментарии.
 */
export function нормализовать(текст) {
  if (!текст) return '';
  return String(текст)
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/https?:\/\/\S+/g, ' ')          // ссылки
    .replace(/@[a-z0-9._]+/gi, ' ')            // упоминания
    .replace(/[^\p{L}\p{N}\s]+/gu, ' ')        // пунктуация и эмодзи
    .replace(/\s+/g, ' ')
    .trim();
}

/** Слова длиннее одной буквы. Предлоги оставляем: они держат структуру фразы. */
export function токены(текст) {
  const н = нормализовать(текст);
  return н ? н.split(' ').filter((w) => w.length > 1) : [];
}

/**
 * Грубое усечение слова до основы — первые 5 символов.
 *
 * Это НЕ морфология, и она не нужна: задача — чтобы «отправлялись» и
 * «отправляли», «сервер» и «сервера», «оказалась» и «оказался» попадали
 * в одну корзину. Русский язык склоняет и спрягает окончания, а спамер
 * перефразирует, меняя ровно их. Замеры на живых парах текстов: без усечения
 * перефразировка давала схожесть 0.58, с усечением — 0.71.
 * 5 символов — компромисс: 4 склеивает разные слова, 6 уже режет мимо основы.
 */
export function основа(слово) {
  return слово.length <= 5 ? слово : слово.slice(0, 5);
}

/** Множество основ слов — сравнение, устойчивое к склонению. */
export function основы(текст) {
  return new Set(токены(текст).map(основа));
}

/**
 * Символьные n-граммы по нормализованному тексту.
 *
 * Ловят то, что не ловят слова: перестановки, опечатки, склейки, замену
 * слова на однокоренное. Работают на любой длине, в том числе на текстах
 * из 2–3 слов, где словных шинглов просто нет.
 */
export function символьныеНграммы(текст, n = 4) {
  const s = нормализовать(текст).replace(/ /g, '_');
  const набор = new Set();
  if (s.length < n) return s ? new Set([s]) : набор;
  for (let i = 0; i + n <= s.length; i++) набор.add(s.slice(i, i + n));
  return набор;
}

/**
 * Шинглы — скользящие окна из n подряд идущих слов.
 *
 * Почему шинглы, а не просто множество слов: «мы починили корзину» и
 * «корзину починили мы» как мешки слов идентичны, но как тексты различны.
 * Шингл ловит порядок. n=3 (триграммы) — обычный компромисс для коротких
 * текстов: n=2 даёт много ложных совпадений, n=4 пропускает перестановки.
 */
export function шинглы(текст, n = 3) {
  const сл = токены(текст);
  if (сл.length === 0) return new Set();
  if (сл.length < n) return new Set([сл.join(' ')]); // короткий текст — целиком
  const набор = new Set();
  for (let i = 0; i <= сл.length - n; i++) набор.add(сл.slice(i, i + n).join(' '));
  return набор;
}

/** Коэффициент Жаккара: |пересечение| / |объединение|. 1 — одинаковы. */
export function жаккар(A, B) {
  if (A.size === 0 && B.size === 0) return 1;
  if (A.size === 0 || B.size === 0) return 0;
  let общих = 0;
  for (const x of A) if (B.has(x)) общих++;
  return общих / (A.size + B.size - общих);
}

/** Расстояние Левенштейна, две строки. Память O(min) — хватает для 500 символов. */
export function левенштейн(a, b) {
  if (a === b) return 0;
  if (!a.length) return b.length;
  if (!b.length) return a.length;
  if (a.length < b.length) [a, b] = [b, a];
  let пред = Array.from({ length: b.length + 1 }, (_, i) => i);
  for (let i = 1; i <= a.length; i++) {
    const тек = [i];
    for (let j = 1; j <= b.length; j++) {
      тек[j] = Math.min(
        пред[j] + 1,                                   // удаление
        тек[j - 1] + 1,                                // вставка
        пред[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1), // замена
      );
    }
    пред = тек;
  }
  return пред[b.length];
}

/**
 * Схожесть двух текстов, 0..1. Главная функция защиты от «похожих ответов».
 *
 * ПОЧЕМУ НЕ ОДНА МЕТРИКА
 *
 * Первая версия считала только Жаккар по словным триграммам — так обычно и
 * пишут. На живых примерах она провалилась: перефразировка, которую человек
 * опознаёт как один и тот же комментарий
 *   «Проверьте, уходит ли заявка с формы на сервер… письма не отправлялись»
 *   «Проверьте, доходит ли заявка с формы до сервера… письма не уходили»
 * дала всего 0.17 — то есть прошла бы любой разумный порог. Причина в русской
 * морфологии: меняется одно окончание, и словная триграмма уже не совпадает.
 *
 * Поэтому считаются ЧЕТЫРЕ сигнала и берётся МАКСИМУМ. Замеры на паре выше:
 *   словные триграммы  0.17  ← слепы к склонению
 *   основы слов        0.71  ← ловят перефразировку
 *   символьные 4-граммы 0.61  ← ловят перестановки и опечатки
 *   Левенштейн         0.81  ← ловит общий каркас фразы
 * Максимум = 0.81, порог 0.45 → отказ. Так и надо.
 *
 * Максимум, а не среднее, выбран сознательно: усреднение размывает сильный
 * сигнал тремя слабыми, а нам нужно поймать похожесть хоть по одному
 * признаку. Цена — иногда отказ хорошему ответу; она приемлема, потому что
 * пропущенный шаблон стоит аккаунта, а лишний отказ стоит одного ответа.
 *
 * Левенштейн считается только для текстов до 600 символов: он O(n·m), а
 * выше лимита площадки (500) всё равно ничего не бывает.
 */
export function схожесть(текстA, текстB, { n = 3, символьныхN = 4 } = {}) {
  const нA = нормализовать(текстA);
  const нB = нормализовать(текстB);
  if (!нA && !нB) return 1;
  if (!нA || !нB) return 0;
  if (нA === нB) return 1;

  const сигналы = [
    жаккар(шинглы(текстA, n), шинглы(текстB, n)),
    жаккар(основы(текстA), основы(текстB)),
    жаккар(символьныеНграммы(текстA, символьныхN), символьныеНграммы(текстB, символьныхN)),
  ];

  if (нA.length <= 600 && нB.length <= 600) {
    const макс = Math.max(нA.length, нB.length);
    сигналы.push(1 - левенштейн(нA, нB) / макс);
  }

  return Math.max(...сигналы);
}

/** Раскладка по сигналам — для отладки и для объяснения отказа человеку. */
export function схожестьПодробно(текстA, текстB, { n = 3, символьныхN = 4 } = {}) {
  const нA = нормализовать(текстA);
  const нB = нормализовать(текстB);
  const макс = Math.max(нA.length, нB.length) || 1;
  return {
    словныеШинглы: жаккар(шинглы(текстA, n), шинглы(текстB, n)),
    основыСлов: жаккар(основы(текстA), основы(текстB)),
    символьные: жаккар(символьныеНграммы(текстA, символьныхN), символьныеНграммы(текстB, символьныхN)),
    левенштейн: нA && нB ? 1 - левенштейн(нA, нB) / макс : 0,
    итог: схожесть(текстA, текстB, { n, символьныхN }),
  };
}

