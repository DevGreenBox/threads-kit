/**
 * ПРЕДОХРАНИТЕЛИ. Самый важный файл во всём мониторинге.
 *
 * ЗАЧЕМ ОН СУЩЕСТВУЕТ
 *
 * Главный риск автоматизации в Threads — не юридический, а поведенческий.
 * Площадка не подаёт в суд, она банит. Банят за признаки inauthentic behavior:
 *   • похожие ответы под постами разных авторов,
 *   • массовые действия ровным ритмом,
 *   • шаблонные комментарии,
 *   • активность круглые сутки без сна.
 * Эскалация: rate limit → action block → блокировка аккаунта.
 *
 * Аккаунт восстанавливать нечем. Поэтому все лимиты здесь стоят на уровне
 * 5–10% от того, что РАЗРЕШАЕТ API. Разрешено 1000 ответов в сутки — здесь
 * потолок 80, и правкой конфига его не поднять (см. ЖЁСТКИЙ_МАКСИМУМ).
 *
 * ПРИНЦИП: отказать дешевле, чем отправить.
 * Любая неоднозначность трактуется как «не отправлять». Пропущенный
 * хороший комментарий стоит ноль. Отправленный плохой стоит аккаунт.
 *
 * ЧТО ЗДЕСЬ ВНУТРИ
 *   ЖЁСТКИЙ_МАКСИМУМ    — потолок, который нельзя поднять конфигом
 *   схожесть()          — детектор похожих текстов (шинглы + Жаккар / Левенштейн)
 *   Журнал              — append-only JSONL всех действий и отказов
 *   Предохранители      — единая точка проверки перед каждой отправкой
 */

