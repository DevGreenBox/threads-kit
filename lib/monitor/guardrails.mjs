/**
 * Append-only журнал в формате JSONL: одна строка — одно событие.
 *
 * Почему JSONL и только добавление: журнал должен пережить падение процесса
 * на середине записи и должен быть доказательством. Перезапись файла целиком
 * позволила бы задним числом «потерять» неудобную запись; здесь это невозможно.
 * Читается grep'ом, склеивается cat'ом.
 */
export class Журнал {
  constructor(путь = 'state/actions.jsonl') {
    this.путь = resolve(путь);
    mkdirSync(dirname(this.путь), { recursive: true });
  }

  записать(событие) {
    const строка = JSON.stringify({ время: new Date().toISOString(), ...событие });
    appendFileSync(this.путь, `${строка}\n`, 'utf8');
    return строка;
  }

  /** Все события, опционально не старше указанного числа дней. */
  прочитать({ дней = null } = {}) {
    if (!existsSync(this.путь)) return [];
    const порог = дней == null ? null : Date.now() - дней * 86400000;
    const записи = [];
    for (const стр of readFileSync(this.путь, 'utf8').split('\n')) {
      if (!стр.trim()) continue;
      try {
        const з = JSON.parse(стр);
        if (порог && new Date(з.время).getTime() < порог) continue;
        записи.push(з);
      } catch {
        // Битая строка (например, обрыв на записи) не должна валить чтение.
      }
    }
    return записи;
  }
}

// ─────────────────────── вспомогательное состояние ───────────────────────

function читатьJSON(путь, поУмолчанию) {
  try {
    return JSON.parse(readFileSync(путь, 'utf8'));
  } catch {
    return поУмолчанию;
  }
}

function писатьJSON(путь, данные) {
  mkdirSync(dirname(путь), { recursive: true });
  const врем = `${путь}.tmp`;
  writeFileSync(врем, JSON.stringify(данные, null, 2), 'utf8');
  renameSync(врем, путь);
}

/** Час в заданной таймзоне без внешних библиотек — через Intl. */
export function часВТаймзоне(таймзона, когда = new Date()) {
  try {
    const ч = new Intl.DateTimeFormat('ru-RU', {
      timeZone: таймзона,
      hour: 'numeric',
      hour12: false,
    }).format(когда);
    return Number(ч) % 24;
  } catch {
    // Неизвестная таймзона: возвращаем UTC и об этом сообщит проверка.
    return когда.getUTCHours();
  }
}

