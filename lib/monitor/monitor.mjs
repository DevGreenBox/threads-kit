/**
 * ЦИКЛ МОНИТОРИНГА.
 *
 * Что делает: берёт темы из конфига, ищет через официальный keyword_search,
 * отбрасывает шум, скорит найденное по релевантности и свежести и кладёт
 * кандидатов в очередь state/queue.jsonl. На этом останавливается.
 *
 * ⚠️ ЭТОТ ФАЙЛ НИЧЕГО НЕ ПУБЛИКУЕТ. Он только собирает очередь. Тексты
 * пишет субагент (agents/threads-monitor.md), отправку разрешают
 * предохранители. Разделение намеренное: сбор данных безопасен и его можно
 * гонять свободно, отправка — нет.
 *
 * ИДЕМПОТЕНТНОСТЬ
 * Повторный запуск не должен обработать тот же пост дважды. Обеспечивается
 * файлом state/seen.json: там id всех постов, которые монитор когда-либо
 * видел. Проверка идёт ДО постановки в очередь, поэтому даже если процесс
 * упал после записи в seen — пост просто не попадёт в очередь, что безопасно
 * (потерять кандидата не страшно, отправить дубль — страшно).
 *
 * Запуск:
 *   node lib/monitor/monitor.mjs --config config/monitor.json
 *   node lib/monitor/monitor.mjs --config config/monitor.json --dry-run
 */

import { readFileSync, writeFileSync, mkdirSync, appendFileSync, renameSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { КлиентThreads, ОшибкаЛимита, ОшибкаТокена, scrubToken } from './api.mjs';
import { Предохранители, Журнал, нормализовать, схожесть } from './guardrails.mjs';

// ───────────────────────── файлы состояния ─────────────────────────

function читатьJSON(путь, поУмолчанию) {
  try {
    return JSON.parse(readFileSync(путь, 'utf8'));
  } catch {
    return поУмолчанию;
  }
}

function писатьJSON(путь, данные) {
  mkdirSync(dirname(путь), { recursive: true });
  const врем = `${путь}.tmp`;
  writeFileSync(врем, JSON.stringify(данные, null, 2), 'utf8');
  renameSync(врем, путь);
}

/**
 * Реестр уже виденных постов — основа идемпотентности.
 *
 * Храним id + время первой встречи. Записи старше 180 дней выбрасываем:
 * пост той давности в поиск RECENT уже не вернётся, а файл иначе растёт вечно.
 */
export class РеестрВиденных {
  constructor(путь = 'state/seen.json') {
    this.путь = resolve(путь);
    this.данные = читатьJSON(this.путь, { версия: 1, посты: {} });
    if (!this.данные.посты) this.данные.посты = {};
  }

  виден(id) {
    return Boolean(this.данные.посты[id]);
  }

  отметить(id, пометка = {}) {
    if (!this.данные.посты[id]) {
      this.данные.посты[id] = { впервые: Date.now(), ...пометка };
    }
  }

  сохранить() {
    const порог = Date.now() - 180 * 86400000;
    for (const [id, з] of Object.entries(this.данные.посты)) {
      if ((з?.впервые ?? 0) < порог) delete this.данные.посты[id];
    }
    писатьJSON(this.путь, this.данные);
  }

  get размер() {
    return Object.keys(this.данные.посты).length;
  }
}

/** Очередь кандидатов: append-only JSONL, как и журнал. */
export class Очередь {
  constructor(путь = 'state/queue.jsonl') {
    this.путь = resolve(путь);
    mkdirSync(dirname(this.путь), { recursive: true });
  }

  добавить(кандидат) {
    appendFileSync(this.путь, `${JSON.stringify(кандидат)}\n`, 'utf8');
  }

  прочитать() {
    if (!existsSync(this.путь)) return [];
    const out = [];
    for (const с of readFileSync(this.путь, 'utf8').split('\n')) {
      if (!с.trim()) continue;
      try {
        out.push(JSON.parse(с));
      } catch {
        /* битую строку пропускаем */
      }
    }
    return out;
  }

  /** id постов, уже стоящих в очереди — вторая линия защиты от дублей. */
  идентификаторы() {
    return new Set(this.прочитать().map((к) => к.postId));
  }
}

// ───────────────────────── фильтры шума ─────────────────────────

/**
 * Причины отбросить пост. Возвращает строку-причину или null, если пост годен.
 *
 * Почему отбрасываем «слишком популярные»: под постом на 300 ответов наш
 * комментарий не увидит никто, а выглядеть он будет как попытка влезть
 * в тренд. Затоптанные ветки — худшее соотношение пользы к риску.
 */
export function причинаОтбросить(пост, настройки, контекст = {}) {
  const {
    свойUsername = null,
    стопСлова = [],
    максВозрастЧасов = 48,
    минДлинаПоста = 80,
    максОтветовВВетке = 60,
    минСловСовпадения = 1,
  } = настройки;

  const текст = String(пост.text || '');
  const автор = String(пост.username || '').toLowerCase();

  if (!пост.id) return 'нет id';
  if (!текст.trim()) return 'пустой текст (картинка или видео без подписи)';

  // Свои посты. keyword_search без одобренного скоупа возвращает именно их —
  // отвечать себе же в цикле бессмысленно и выглядит странно.
  if (свойUsername && автор === String(свойUsername).toLowerCase()) {
    return 'это наш собственный пост';
  }

  if (текст.length < минДлинаПоста) {
    return `слишком короткий пост (${текст.length} симв.) — по нему нечего сказать по существу`;
  }

  // Возраст. По старому посту отвечать поздно: ветка мертва, а всплытие
  // трёхдневного поста выглядит как выкапывание.
  if (пост.timestamp) {
    const возрастЧ = (Date.now() - new Date(пост.timestamp).getTime()) / 3600000;
    if (!Number.isFinite(возрастЧ)) return 'непонятная дата публикации';
    if (возрастЧ > максВозрастЧасов) {
      return `старый пост (${Math.round(возрастЧ)} ч, предел ${максВозрастЧасов} ч)`;
    }
    if (возрастЧ < 0) return 'дата публикации в будущем — пропускаем';
  }

  // Затоптанная ветка.
  const ответов = Number(пост.replies_count ?? пост.reply_count ?? NaN);
  if (Number.isFinite(ответов) && ответов > максОтветовВВетке) {
    return `затоптанная ветка (${ответов} ответов, предел ${максОтветовВВетке})`;
  }

  // Стоп-слова: политика, конфликты, чужие уязвимости, продажи чужого.
  const н = нормализовать(текст);
  for (const слово of стопСлова) {
    const нс = нормализовать(слово);
    if (нс && н.includes(нс)) return `стоп-слово «${слово}»`;
  }

  // Репост/цитата: отвечаем на первоисточник, а не на пересказ.
  if (пост.is_quote_post === true) return 'это цитата чужого поста, а не первоисточник';

  // Совпадение по теме должно быть настоящим, а не случайным.
  if (контекст.ключевые && контекст.ключевые.length) {
    const попаданий = контекст.ключевые.filter((к) => н.includes(нормализовать(к))).length;
    if (попаданий < минСловСовпадения) {
      return 'ключевое слово в тексте не найдено (поиск дал случайное совпадение)';
    }
  }

  return null;
}

// ───────────────────────── скоринг ─────────────────────────

/**
 * Оценка ветки, 0..1. Чем выше, тем полезнее отвечать.
 *
 * Три составляющие:
 *   свежесть      — чем новее, тем живее ветка (первый час решает)
 *   релевантность — сколько ключевых слов темы реально в тексте
 *   обсуждаемость — есть ли разговор, но не толпа
 *
 * Веса заданы так, чтобы свежесть не могла перебить релевантность: отвечать
 * быстро на не свою тему хуже, чем спокойно на свою.
 */
export function оценить(пост, { ключевые = [], вес = {} } = {}) {
  const в = { свежесть: 0.35, релевантность: 0.45, обсуждаемость: 0.2, ...вес };
  const текст = нормализовать(пост.text || '');

  let свежесть = 0.5;
  if (пост.timestamp) {
    const ч = (Date.now() - new Date(пост.timestamp).getTime()) / 3600000;
    // 0–2 ч → ~1, 12 ч → ~0.5, 48 ч → ~0.15. Плавное затухание.
    свежесть = Number.isFinite(ч) ? 1 / (1 + Math.max(0, ч) / 12) : 0.5;
  }

  const попаданий = ключевые.filter((к) => текст.includes(нормализовать(к))).length;
  const релевантность = ключевые.length ? Math.min(1, попаданий / Math.min(3, ключевые.length)) : 0.5;

  const ответов = Number(пост.replies_count ?? пост.reply_count ?? NaN);
  let обсуждаемость = 0.5;
  if (Number.isFinite(ответов)) {
    // Оптимум 1–15 ответов: разговор начался, толпы нет.
    обсуждаемость = ответов === 0 ? 0.4 : ответов <= 15 ? 1 : Math.max(0.1, 15 / ответов);
  } else if (пост.has_replies === true) {
    обсуждаемость = 0.7;
  }

  const итог = в.свежесть * свежесть + в.релевантность * релевантность + в.обсуждаемость * обсуждаемость;
  return {
    итог: Number(итог.toFixed(4)),
    свежесть: Number(свежесть.toFixed(3)),
    релевантность: Number(релевантность.toFixed(3)),
    обсуждаемость: Number(обсуждаемость.toFixed(3)),
    попаданий,
  };
}

// ───────────────────────── основной прогон ─────────────────────────

/**
 * Один проход мониторинга по всем темам конфига.
 *
 * @param {object} опции
 * @param {object} опции.конфиг    разобранный config/monitor.json
 * @param {КлиентThreads} опции.клиент
 * @param {Предохранители} опции.предохранители
 * @param {boolean} [опции.dryRun] не писать в состояние
 */
export async function прогон({
  конфиг,
  клиент,
  предохранители,
  реестр = null,
  очередь = null,
  журнал = null,
  dryRun = false,
  лог = console.log,
} = {}) {
  const темы = Array.isArray(конфиг?.темы) ? конфиг.темы : [];
  const р = реестр || new РеестрВиденных(конфиг?.пути?.виденные || 'state/seen.json');
  const оч = очередь || new Очередь(конфиг?.пути?.очередь || 'state/queue.jsonl');
  const ж = журнал || предохранители?.журнал || new Журнал(конфиг?.пути?.журнал || 'state/actions.jsonl');

  const итоги = {
    тем: темы.length,
    запросов: 0,
    найдено: 0,
    ужеВидели: 0,
    отброшено: 0,
    вОчередь: 0,
    причиныОтказов: {},
    ошибки: [],
    остановлено: false,
  };

  // Стоп-кран проверяется первым: если он опущен, не делаем даже поиск.
  if (предохранители.стопКранОпущен()) {
    лог(
      '⛔ Опущен стоп-кран: ' +
        `${предохранители.состояние.стопКран.причина}. Мониторинг не запускается. ` +
        'Снять может только человек — см. state/guardrails.json и журнал.',
    );
    итоги.остановлено = true;
    return итоги;
  }

  const бюджетПоиска = предохранители.наст.поисковыхЗапросовВСутки;
  const уже = клиент.квоты.израсходовано('search');

  const кандидаты = [];

  for (const тема of темы) {
    const имя = тема?.имя || тема?.запрос || '(без имени)';
    const фразы = Array.isArray(тема?.запросы) ? тема.запросы : [тема?.запрос].filter(Boolean);
    const ключевые = Array.isArray(тема?.ключевые) ? тема.ключевые : фразы;

    for (const фраза of фразы) {
      if (итоги.запросов + уже >= бюджетПоиска) {
        лог(`⏸ Бюджет поиска на сутки исчерпан (${бюджетПоиска}). Остальные темы — в следующий прогон.`);
        break;
      }
      const разрешение = предохранители.проверитьПоиск({ запрос: фраза });
      if (!разрешение.можно) {
        итоги.остановлено = true;
        break;
      }

      let результат;
      try {
        итоги.запросов++;
        результат = await клиент.keywordSearch({
          q: фраза,
          searchMode: тема?.режим || 'KEYWORD',
          searchType: тема?.тип || 'RECENT',
          limit: Math.min(Number(тема?.лимит) || 25, 100),
        });
      } catch (ошибка) {
        const текст = scrubToken(ошибка?.message || String(ошибка));
        итоги.ошибки.push({ фраза, ошибка: текст, класс: ошибка?.name });
        ж.записать({ событие: 'ошибка_поиска', фраза, класс: ошибка?.name, сообщение: текст });

        const вердикт = предохранители.разобратьОшибкуAPI(ошибка);
        if (вердикт.стопКран) {
          лог(`⛔ Стоп-кран: ${текст}`);
          итоги.остановлено = true;
          break;
        }
        // Лимит площадки — прекращаем прогон спокойно, без стоп-крана.
        if (ошибка instanceof ОшибкаЛимита) {
          лог(`⏸ Лимит площадки, прогон прекращён: ${текст}`);
          break;
        }
        continue;
      }

      ж.записать({
        событие: 'поиск',
        фраза,
        тема: имя,
        найдено: результат.посты.length,
        пустой: результат.пустой,
      });

      if (результат.пустой) {
        лог(`  · «${фраза}» — ничего (квота не израсходована)`);
        continue;
      }

      for (const пост of результат.посты) {
        итоги.найдено++;

        // ИДЕМПОТЕНТНОСТЬ: видели — мимо, без каких-либо действий.
        if (р.виден(пост.id)) {
          итоги.ужеВидели++;
          continue;
        }

        const причина = причинаОтбросить(пост, { ...(конфиг?.фильтры || {}), свойUsername: конфиг?.свойUsername, стопСлова: конфиг?.стопСлова || [] }, { ключевые });
        if (причина) {
          итоги.отброшено++;
          итоги.причиныОтказов[причина] = (итоги.причиныОтказов[причина] || 0) + 1;
          if (!dryRun) р.отметить(пост.id, { отброшен: причина });
          ж.записать({ событие: 'отброшен', postId: пост.id, причина, тема: имя });
          continue;
        }

        const оценка = оценить(пост, { ключевые, вес: конфиг?.весаСкоринга });
        const минОценка = Number(конфиг?.фильтры?.минОценка ?? 0.4);
        if (оценка.итог < минОценка) {
          итоги.отброшено++;
          const п = `низкая оценка ${оценка.итог} < ${минОценка}`;
          итоги.причиныОтказов[п] = (итоги.причиныОтказов[п] || 0) + 1;
          if (!dryRun) р.отметить(пост.id, { отброшен: п });
          continue;
        }

        кандидаты.push({
          postId: пост.id,
          author: пост.username || null,
          permalink: пост.permalink || null,
          timestamp: пост.timestamp || null,
          текст: пост.text || '',
          тема: имя,
          фраза,
          ключевые,
          оценка,
        });
      }
    }
    if (итоги.остановлено) break;
  }

  // Сортируем по оценке: сверху — самое полезное.
  кандидаты.sort((a, b) => b.оценка.итог - a.оценка.итог);

  // Отбрасываем кандидатов, похожих ДРУГ НА ДРУГА в рамках одного прогона:
  // два поста об одном и том же неизбежно получат похожие ответы, а это
  // ровно то, за что банят. Оставляем тот, у кого оценка выше.
  const отобранные = [];
  const порогПохожестиПостов = Number(конфиг?.фильтры?.максСхожестьПостов ?? 0.5);
  for (const к of кандидаты) {
    const близкий = отобранные.find((о) => схожесть(о.текст, к.текст) >= порогПохожестиПостов);
    if (близкий) {
      итоги.отброшено++;
      const п = 'дубль темы внутри прогона (пост похож на другого кандидата)';
      итоги.причиныОтказов[п] = (итоги.причиныОтказов[п] || 0) + 1;
      if (!dryRun) р.отметить(к.postId, { отброшен: п });
      ж.записать({ событие: 'отброшен', postId: к.postId, причина: п, похожНа: близкий.postId });
      continue;
    }
    отобранные.push(к);
  }

  const вОчереди = оч.идентификаторы();
  const потолокОчереди = Number(конфиг?.фильтры?.максКандидатовЗаПрогон ?? 10);

  for (const к of отобранные.slice(0, потолокОчереди)) {
    if (вОчереди.has(к.postId)) {
      итоги.ужеВидели++;
      continue;
    }
    const запись = { ...к, поставлен: new Date().toISOString(), статус: 'новый' };
    if (!dryRun) {
      оч.добавить(запись);
      р.отметить(к.postId, { вОчереди: true });
      ж.записать({ событие: 'в_очередь', postId: к.postId, тема: к.тема, оценка: к.оценка.итог });
    }
    итоги.вОчередь++;
  }

  if (!dryRun) р.сохранить();

  итоги.виденныхВсего = р.размер;
  return итоги;
}

// ───────────────────────── запуск из терминала ─────────────────────────

function разобратьАргументы(argv) {
  const о = { config: 'config/monitor.json', dryRun: false };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--config') о.config = argv[++i];
    else if (argv[i] === '--dry-run') о.dryRun = true;
  }
  return о;
}

async function main() {
  const арг = разобратьАргументы(process.argv.slice(2));
  const путьКонфига = resolve(арг.config);

  if (!existsSync(путьКонфига)) {
    console.error(
      `Не найден конфиг: ${путьКонфига}\n` +
        'Скопируйте пример: cp config/monitor.example.json config/monitor.json',
    );
    process.exit(1);
  }

  let конфиг;
  try {
    конфиг = JSON.parse(readFileSync(путьКонфига, 'utf8'));
  } catch (e) {
    console.error(`Конфиг ${путьКонфига} не разбирается как JSON: ${e.message}`);
    process.exit(1);
  }

  if (!process.env.THREADS_ACCESS_TOKEN) {
    console.error(
      'Нет переменной окружения THREADS_ACCESS_TOKEN.\n' +
        'Как получить токен — config/README.md. Запуск без токена невозможен: ' +
        'поиск идёт через официальный API.',
    );
    process.exit(1);
  }

  const журнал = new Журнал(конфиг?.пути?.журнал || 'state/actions.jsonl');
  const предохранители = new Предохранители({
    конфиг: конфиг?.предохранители || {},
    путьСостояния: конфиг?.пути?.предохранители || 'state/guardrails.json',
    журнал,
  });

  if (предохранители.зажатые?.length) {
    console.log('⚠️ Некоторые настройки конфига зажаты жёстким максимумом:');
    for (const з of предохранители.зажатые) {
      console.log(`   ${з.имя}: в конфиге ${з.было} → применено ${з.стало} (предел ${з.предел})`);
    }
  }

  const клиент = new КлиентThreads({
    userId: конфиг?.userId || 'me',
    путьКвот: конфиг?.пути?.квоты || 'state/quota.json',
    журнал: (с) => журнал.записать(с),
  });

  console.log(`Мониторинг: тем ${конфиг?.темы?.length ?? 0}${арг.dryRun ? ', режим dry-run' : ''}`);

  try {
    const итоги = await прогон({ конфиг, клиент, предохранители, журнал, dryRun: арг.dryRun });
    console.log('\n── Итоги прогона ──');
    console.log(`Запросов к API:   ${итоги.запросов}`);
    console.log(`Найдено постов:   ${итоги.найдено}`);
    console.log(`Уже видели:       ${итоги.ужеВидели}`);
    console.log(`Отброшено:        ${итоги.отброшено}`);
    console.log(`В очередь:        ${итоги.вОчередь}`);
    if (Object.keys(итоги.причиныОтказов).length) {
      console.log('\nПочему отбрасывали:');
      for (const [п, н] of Object.entries(итоги.причиныОтказов).sort((a, b) => b[1] - a[1])) {
        console.log(`  ${н}× ${п}`);
      }
    }
    const б = предохранители.бюджет();
    console.log(
      `\nБюджет ответов: ${б.ответовЗаСутки}/${б.потолокОтветов} за сутки ` +
        `(жёсткий максимум ${б.жёсткийМаксимум})`,
    );
    if (итоги.остановлено) {
      console.log('\n⛔ Прогон остановлен предохранителями. Смотрите журнал.');
      process.exit(2);
    }
  } catch (ошибка) {
    if (ошибка instanceof ОшибкаТокена) {
      console.error(`\n⛔ ${scrubToken(ошибка.message)}`);
      process.exit(3);
    }
    console.error(`\n⛔ Прогон упал: ${scrubToken(ошибка?.message || String(ошибка))}`);
    process.exit(1);
  }
}

