/**
 * Чтение файла .env — без зависимостей.
 *
 * Зачем отдельный файл: вся документация набора говорит «положите токен
 * в .env», а Node сам такие файлы не читает. Без этого модуля человек
 * делает всё по инструкции и получает «нет переменной окружения» —
 * ошибку, которая выглядит как поломка программы, хотя он всё сделал верно.
 *
 * Правила разбора намеренно простые и предсказуемые:
 *   КЛЮЧ=значение        — обычная строка
 *   КЛЮЧ="значение"      — кавычки снимаются (одинарные и двойные)
 *   export КЛЮЧ=значение — приставка export игнорируется
 *   # комментарий        — строка целиком пропускается
 *
 * Уже установленную переменную окружения файл НЕ перебивает: то, что
 * человек задал в терминале руками, всегда главнее файла.
 */

import { existsSync, readFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Разобрать содержимое .env в объект. Экспортируется ради проверяемости. */
export function разобратьEnv(текст) {
  const итог = {};
  for (const сырая of String(текст).split(/\r?\n/)) {
    const строка = сырая.trim();
    if (!строка || строка.startsWith('#')) continue;

    const без = строка.startsWith('export ') ? строка.slice(7).trim() : строка;
    const знак = без.indexOf('=');
    if (знак <= 0) continue;

    const ключ = без.slice(0, знак).trim();
    if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(ключ)) continue;

    let значение = без.slice(знак + 1).trim();
    const парные =
      (значение.startsWith('"') && значение.endsWith('"')) ||
      (значение.startsWith("'") && значение.endsWith("'"));
    if (парные && значение.length >= 2) значение = значение.slice(1, -1);
    else значение = значение.split(' #')[0].trim(); // хвостовой комментарий

    итог[ключ] = значение;
  }
  return итог;
}

/**
 * Подгрузить .env в process.env, если файл есть.
 * Возвращает список подхваченных ключей — по нему видно, что сработало.
 * Отсутствие файла — не ошибка: токен можно задать и переменной окружения.
 */
export function загрузитьEnv(путь = null) {
  const корень = resolve(dirname(fileURLToPath(import.meta.url)), '..');
  const файл = путь ? resolve(путь) : join(корень, '.env');
  if (!existsSync(файл)) return [];

  let разобрано;
  try {
    разобрано = разобратьEnv(readFileSync(файл, 'utf8'));
  } catch {
    return [];
  }

  const подхвачено = [];
  for (const [к, з] of Object.entries(разобрано)) {
    if (process.env[к] === undefined || process.env[к] === '') {
      process.env[к] = з;
      подхвачено.push(к);
    }
  }
  return подхвачено;
}

export default загрузитьEnv;
